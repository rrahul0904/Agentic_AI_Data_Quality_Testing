"""ADE-owned deterministic Search quality/scale regression.

This corpus is generated by ADE and must not be presented as a Cortex Search, Elasticsearch,
Qdrant, or other vendor benchmark. It verifies known-answer ranking, persisted approximate
candidate generation, and records bounded performance observations for regression tracking.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import tempfile
import time

from agentic_data_platform.retrieval import (
    ADESearchIndex,
    DeterministicHashEmbedding,
    RetrievalQuery,
    SearchChunk,
)


QUERY_COUNT = 40
DOCS_PER_QUERY = 6
CORPUS_SIZE = QUERY_COUNT * DOCS_PER_QUERY


def _corpus():
    chunks = []
    expected = {}
    systems = ("airflow", "dbt", "snowflake", "quality")
    for query_index in range(QUERY_COUNT):
        signal = f"signal_q{query_index:03d}"
        target_id = f"target-{query_index:03d}"
        expected[signal] = target_id
        chunks.append(
            SearchChunk(
                target_id,
                f"runbooks/{target_id}.md",
                f"{signal} scheduler recovery canonical incident procedure for data platform operations",
                {"system": systems[query_index % len(systems)], "answer": True},
            )
        )
        for distractor in range(DOCS_PER_QUERY - 1):
            chunks.append(
                SearchChunk(
                    f"noise-{query_index:03d}-{distractor}",
                    f"notes/noise-{query_index:03d}-{distractor}.md",
                    f"generic platform note {query_index} {distractor} about dashboards costs schemas and models",
                    {"system": systems[(query_index + distractor + 1) % len(systems)], "answer": False},
                )
            )
    assert len(chunks) == CORPUS_SIZE
    return chunks, expected


def run() -> dict[str, object]:
    chunks, expected = _corpus()
    with tempfile.TemporaryDirectory(prefix="ade-search-bench-") as temporary:
        index = ADESearchIndex(
            Path(temporary) / "search.db",
            index_name="benchmark",
            embedder=DeterministicHashEmbedding(dimensions=64),
            exact_vector_scan_limit=50,
            lsh_tables=4,
            lsh_bits=8,
            lsh_candidate_limit=200,
        )
        ingest_started = time.perf_counter()
        mutations = index.upsert_many(chunks)
        ingest_seconds = time.perf_counter() - ingest_started

        top1 = 0
        recall_at_5 = 0
        reciprocal_rank = 0.0
        lsh_queries = 0
        failures = []
        query_started = time.perf_counter()
        for signal, expected_id in expected.items():
            hits = index.search(
                RetrievalQuery(f"{signal} scheduler recovery", limit=5),
                lexical_weight=0.7,
                vector_weight=0.2,
                rerank_weight=0.1,
            )
            ids = [str(hit.fields.get("chunk_id")) for hit in hits]
            if hits and hits[0].evidence.get("vector_candidate_strategy") == "sqlite_lsh_approximate":
                lsh_queries += 1
            if ids and ids[0] == expected_id:
                top1 += 1
            if expected_id in ids:
                recall_at_5 += 1
                reciprocal_rank += 1.0 / (ids.index(expected_id) + 1)
            else:
                failures.append({"query": signal, "expected": expected_id, "observed": ids})
        query_seconds = time.perf_counter() - query_started

    top1_rate = top1 / QUERY_COUNT
    recall5_rate = recall_at_5 / QUERY_COUNT
    mrr = reciprocal_rank / QUERY_COUNT
    return {
        "schema_version": 1,
        "benchmark": "ADE deterministic Search regression",
        "dataset_owner": "ADE",
        "vendor_score_claimed": False,
        "corpus_documents": CORPUS_SIZE,
        "queries": QUERY_COUNT,
        "mutations": mutations,
        "top1": round(top1_rate, 6),
        "recall_at_5": round(recall5_rate, 6),
        "mrr": round(mrr, 6),
        "approximate_candidate_queries": lsh_queries,
        "ingest_seconds": round(ingest_seconds, 6),
        "documents_per_second": round(CORPUS_SIZE / ingest_seconds, 3) if ingest_seconds else None,
        "query_seconds": round(query_seconds, 6),
        "average_query_ms": round(query_seconds * 1000 / QUERY_COUNT, 6),
        "failures": failures[:20],
        "passed": (
            top1_rate == 1.0
            and recall5_rate == 1.0
            and mrr == 1.0
            and lsh_queries == QUERY_COUNT
            and not failures
        ),
        "truthfulness": {
            "purpose": "deterministic known-answer local regression",
            "external_dataset_used": False,
            "external_product_score_claimed": False,
            "lsh_is_approximate": True,
            "performance_is_observation_not_sla": True,
        },
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="artifacts/competitive/search-benchmark.json")
    args = parser.parse_args()
    report = run()
    path = Path(args.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())